# 考点:JSON 语法规则的手感 + 用程序验证人肉判断
# 人肉判断答案:
#   样本1 合法;样本2 非法(单引号);样本3 合法(小写 true/null 正是规范);
#   样本4 非法(尾逗号);样本5 合法(\" 是内嵌双引号的转义)
# =============================================
import json

samples = [
    '{"a": 1, "b": 2}',              # ✅ 合法
    "{'a': 1}",                      # ❌ 单引号
    '{"a": true, "b": null}',        # ✅ 合法
    '{"a": 1,}',                     # ❌ 尾逗号
    '{"a": "他说:\\"你好\\""}',      # ✅ 合法
]

for i, s in enumerate(samples, start=1):
    try:
        data = json.loads(s)
        print(f"样本{i}:✅ 合法 → {data}")
    except json.JSONDecodeError as e:
        print(f"样本{i}:❌ 非法 → {e}")
