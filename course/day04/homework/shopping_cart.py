# Day 04 作业 · 编程题 4:购物车结算
# 考点:count 计数、元组拆包遍历、累加器
# 明天预告:prices 这种"名字→单价"的对应关系,字典才是它的真身——
#   查"苹果的单价"要遍历整个列表,1 万种商品就遍历 1 万次,
#   这份别扭是故意留给你的,明天字典一行解决:prices["苹果"]
# =============================================

cart = ["苹果", "牛奶", "苹果", "面包", "牛奶", "苹果"]
prices = [("苹果", 5), ("牛奶", 12), ("面包", 8)]

total = 0                                  # 总价累加器

for name, price in prices:                 # 遍历元组列表,每轮拆包出名字和单价
    quantity = cart.count(name)            # 在购物记录里数这个商品出现几次
    subtotal = quantity * price
    total += subtotal
    print(f"{name} x{quantity} = {subtotal} 元")

print("-" * 20)
print(f"总计:{total} 元")
