raw_comment = """   这个AI客服真是垃圾,回答驴唇不对马嘴!
客服电话13812345678也打不通,   NO ONE CARES!
真是气死我了,做这个产品的都是傻子   
"""

step1 = raw_comment.strip()
step2 = step1.lower()

# ---- F3:敏感词替换 ----
# 敏感词逐个处理:先数出现次数(报告要用),再替换成等长的 *
# "等长"是产品细节:** 比直接删除更能让人看出"这里有词被处理了"
# 明天(Day 03)学了 for 循环,这三段重复代码会被压缩成三行——
# 今天先忍受重复,亲身体会"没有循环的痛",明天的知识才有滋味

count_1 = step2.count("垃圾")            # 数"垃圾"出现几次
step3 = step2.replace("垃圾", "**")      # 替换为等长的两个星号

count_2 = step3.count("傻子")            # 注意:在 step3 上继续数和换
step3 = step3.replace("傻子", "**")      # 结果赋回 step3(累积加工)
# ⚠️ 如果这里不赋值回去(只写 step3.replace(...)),这一步等于白做——
#    字符串不可变,方法返回的新串必须有人接住。可以故意试一次!

count_3 = step3.count("废物")
step3 = step3.replace("废物", "**")

total_replaced = count_1 + count_2 + count_3    # 报告用:总替换词数

print(f"[{step3}]")
print(f"共处理敏感词 {total_replaced} 个")
