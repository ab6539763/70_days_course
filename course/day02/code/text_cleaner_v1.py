# ---- 原始数据 ----
# 用三引号定义多行字符串,模拟从文件读入的原始评论
# 注意:第一行开头和最后都有故意留的空白,这就是要清洗的"脏"
raw_comment = """   这个AI客服真是垃圾,回答驴唇不对马嘴!
客服电话13812345678也打不通,   NO ONE CARES!
真是气死我了,做这个产品的都是傻子   
"""

# ---- F1:去除两端空白 ----
# strip() 剥掉整段文本首尾的空格和换行(中间的不动)
step1 = raw_comment.strip()

# ---- F2:英文统一小写 ----
# lower() 只影响英文字母,中文和数字原样保留
step2 = step1.lower()

# ---- 检查半成品 ----
# 用 [] 包住输出是调试技巧:能看清两端到底还有没有空白
print(f"[{step2}]")
