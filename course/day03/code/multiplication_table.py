# =============================================
# 九九乘法表:嵌套 for 循环的经典训练
# 外层 i = 行号(1~9),内层 j = 列号(1~i)
# 核心认知:外层走一步,内层跑全程;内层的范围随外层变化
# =============================================

# ---- 标准下三角乘法表 ----
for i in range(1, 10):             # 外层:第 1 行到第 9 行
    for j in range(1, i + 1):      # 内层:第 i 行有 i 个算式(含头不含尾所以 i+1)
        # end="\t" 不换行,用制表符对齐(Day 01 的 end 参数第一次干正事)
        print(f"{j}×{i}={j * i}", end="\t")
    print()                        # 内层跑完一行,补换行(空 print = 只换行)
    # ⚠️ 把这个 print() 错误缩进到内层试试:表会"竖"过来——缩进决定归属

print()

# ---- 变式 1:只打印结果为偶数的算式(if 过滤进双层循环) ----
for i in range(1, 10):
    for j in range(1, i + 1):
        if (j * i) % 2 == 0:                   # Day 02 的取余判断偶数
            print(f"{j}×{i}={j * i}", end="\t")
    print()

print()

