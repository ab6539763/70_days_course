# Day 03 作业 · 编程题 3:星号金字塔
# 考点:嵌套循环、行内两段循环(先空格后星号)、end=""
# 规律:第 i 层 = (N - i) 个空格 + (2i - 1) 个星号
# =============================================

N = 5                                  # 层数做成常量,改 9 层只动这里

for i in range(1, N + 1):              # 外层:第 1 到第 N 层
    for _ in range(N - i):             # 内层 1:先打空格(_ 表示用不到循环变量)
        print(" ", end="")
    for _ in range(2 * i - 1):         # 内层 2:再打星号
        print("*", end="")
    print()                            # 本层结束,换行

