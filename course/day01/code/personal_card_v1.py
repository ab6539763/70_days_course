# ---- 输入环节:收集 5 项信息 ----
# input() 会暂停程序等待用户输入,返回值一律是字符串(str)
name = input("请输入你的姓名:")
age = input("请输入你的年龄:")
city = input("请输入你所在的城市:")
job = input("请输入你的期望岗位:")
hours = input("请输入你每天可投入的学习小时数:")

# ---- 输出环节:先原样打印,确认 5 个变量都正确拿到了 ----
# v1 的意义:验证主流程通畅。只有输入输出两个环节,
# 一旦出错,排查范围极小,这就是"小步迭代"的价值。
print(name)
print(age)
print(city)
print(job)
print(hours)
