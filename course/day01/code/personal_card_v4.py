# ---- 常量区 ----
# 把"写死的数字/文本"提取为大写命名的常量,集中放在文件顶部。
# 好处:明年课程改为 90 天时,只需改这里一处,而不是全文找 70。
# 这类散落在代码里的裸数字有个贬义外号叫"魔法数字(magic number)",
# 消灭魔法数字是代码整洁的第一课。
CURRENT_YEAR = 2026        # 当前年份,用于推算出生年份
COURSE_DAYS = 70           # 课程总天数
BANNER_WIDTH = 40          # 横幅宽度(字符数)

# ---- 欢迎横幅 ----
print("=" * BANNER_WIDTH)
print("     欢迎加入 70 天大模型开发训练营")
print("=" * BANNER_WIDTH)

# ---- 输入环节 ----
# 每个 input 的提示语都以冒号结尾并说明期望格式,这是用户体验的细节。
name = input("请输入你的姓名:")
age = int(input("请输入你的年龄(数字):"))
city = input("请输入你所在的城市:")
job = input("请输入你的期望岗位:")
hours = int(input("请输入你每天可投入的学习小时数(数字):"))

# ---- 处理环节 ----
birth_year = CURRENT_YEAR - age      # 出生年份 = 当前年份 - 年龄
total_hours = hours * COURSE_DAYS    # 总学习时长 = 每日小时数 × 课程天数

# ---- 输出环节 ----
card = f"""
┌────────────────────────────────────┐
│          新学员信息卡片              │
├────────────────────────────────────┤
│  姓名:{name}
│  年龄:{age} 岁({birth_year} 年出生)
│  城市:{city}
│  期望岗位:{job}
│  学习投入:每天 {hours} 小时,{COURSE_DAYS} 天共 {total_hours} 小时
└────────────────────────────────────┘
"""
print(card)

print(f"{name},欢迎你!{COURSE_DAYS} 天后,愿你成为一名合格的{job}。")
print(f"从 {city} 出发,每天 {hours} 小时,你的 {total_hours} 小时倒计时,现在开始!")
