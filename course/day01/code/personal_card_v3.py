# ---- 欢迎横幅 ----
# 字符串可以做"乘法":"=" * 40 会生成 40 个等号组成的字符串,
# 这是画分隔线最常用的技巧。
print("=" * 40)
print("     欢迎加入 70 天大模型开发训练营")
print("=" * 40)

# ---- 输入环节 ----
name = input("请输入你的姓名:")
age = int(input("请输入你的年龄:"))
city = input("请输入你所在的城市:")
job = input("请输入你的期望岗位:")
hours = int(input("请输入你每天可投入的学习小时数:"))

# ---- 处理环节 ----
birth_year = 2026 - age
total_hours = hours * 70

# ---- 输出环节:f + """ 多行字符串,一次性组装整张卡片 ----
# 变量 card 里存的是一个带换行的长字符串,一个 print 全部输出。
# 【伏笔】f + 三引号的多行模板,就是 Day 17 起 Prompt 模板的写法。
card = f"""
┌────────────────────────────────────┐
│          新学员信息卡片              │
├────────────────────────────────────┤
│  姓名:{name}
│  年龄:{age} 岁({birth_year} 年出生)
│  城市:{city}
│  期望岗位:{job}
│  学习投入:每天 {hours} 小时,70 天共 {total_hours} 小时
└────────────────────────────────────┘
"""
print(card)

# ---- 个性化欢迎语 ----
print(f"{name},欢迎你!70 天后,愿你成为一名合格的{job}。")
print(f"从 {city} 出发,每天 {hours} 小时,你的 {total_hours} 小时倒计时,现在开始!")
